/**
 * message_alignments - 消息对齐和最小长度要求
 * 
 * 内存对齐的重要性：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                      对齐优化原理                            │
 * │                                                             │
 * │  ┌─────────────────┐    ┌─────────────────┐                │
 * │  │   未对齐访问     │    │    对齐访问      │                │
 * │  │                │    │                │                │
 * │  │ • 跨缓存行      │    │ • 单缓存行      │                │
 * │  │ • 多次内存访问   │    │ • 一次内存访问   │                │
 * │  │ • 性能损失      │    │ • 最优性能      │                │
 * │  │ • 硬件额外开销   │    │ • 硬件友好      │                │
 * │  └─────────────────┘    └─────────────────┘                │
 * └─────────────────────────────────────────────────────────────┘
 */
enum message_alignments {
	/* 消息填充对齐倍数 (16字节)
	 * 
	 * 为什么选择16字节对齐：
	 * • SIMD优化：现代CPU的SIMD指令(SSE/AVX)最适合16字节对齐
	 * • 加密算法：ChaCha20和Poly1305的内部块大小友好
	 * • 缓存行：减少缓存行跨越，提高内存访问效率
	 * • DMA优化：网络硬件的DMA传输通常偏好16字节对齐
	 * 
	 * 对齐影响：
	 * - 所有消息长度都会被对齐到16的倍数
	 * - 小于16字节的消息会被填充到16字节
	 * - 大消息的尾部会被填充到对齐边界 */
	MESSAGE_PADDING_MULTIPLE = 16,
	
	/* 最小消息长度 (32字节)
	 * 计算：message_data_len(0) = 16 + 0 + 16 = 32字节
	 * 
	 * 组成分析：
	 * • 16字节：固定头部 (header + key_idx + counter)
	 * • 0字节：空的IP数据包 (keepalive消息)
	 * • 16字节：Poly1305 MAC标签
	 * 
	 * 用途：
	 * - keepalive消息：维持NAT映射和连接状态
	 * - 空数据包：某些协议测试场景
	 * - 缓冲区预分配：网络栈的最小缓冲区大小 */
	MESSAGE_MINIMUM_LENGTH = message_data_len(0)
};

