/**
 * noise_lengths - Noise 协议框架中使用的各种数据长度定义
 * 
 * 长度映射关系：
 * ┌─────────────────────┐    ┌─────────────────────┐    ┌─────────────────────┐
 * │   WireGuard 概念    │    │    Noise 协议名称   │    │     实际字节长度     │
 * ├─────────────────────┼────┼─────────────────────┼────┼─────────────────────┤
 * │   公钥 (Public)     │───►│ NOISE_PUBLIC_KEY    │───►│    32 字节          │
 * │   私钥 (Private)    │───►│ NOISE_PUBLIC_KEY    │───►│    32 字节          │
 * │   对称密钥 (Key)    │───►│ NOISE_SYMMETRIC_KEY │───►│    32 字节          │
 * │   时间戳 (Timestamp)│───►│ NOISE_TIMESTAMP     │───►│    12 字节          │
 * │   认证标签 (MAC)    │───►│ NOISE_AUTHTAG       │───►│    16 字节          │
 * │   哈希值 (Hash)     │───►│ NOISE_HASH          │───►│    32 字节          │
 * └─────────────────────┘    └─────────────────────┘    └─────────────────────┘
 * 
 * 这些长度基于以下加密算法的规格：
 * • Curve25519: 32字节公钥/私钥（椭圆曲线DH）
 * • ChaCha20Poly1305: 32字节密钥 + 16字节认证标签（AEAD）
 * • BLAKE2s: 32字节哈希输出（密码学哈希函数）
 */
enum noise_lengths {
	/* Curve25519 椭圆曲线公钥长度 (32字节)
	 * 用于：静态公钥、临时公钥、DH 计算结果 */
	NOISE_PUBLIC_KEY_LEN = CURVE25519_KEY_SIZE,
	
	/* ChaCha20Poly1305 对称密钥长度 (32字节)
	 * 用于：传输密钥、链式密钥、握手密钥 */
	NOISE_SYMMETRIC_KEY_LEN = CHACHA20POLY1305_KEY_SIZE,
	
	/* 时间戳结构长度 (12字节 = 8字节时间 + 4字节毫秒)
	 * 用于：握手重放保护、时间同步验证
	 * 结构：u64 秒数 + u32 毫秒数 */
	NOISE_TIMESTAMP_LEN = sizeof(u64) + sizeof(u32),
	
	/* Poly1305 认证标签长度 (16字节)
	 * 用于：AEAD加密的完整性验证标签 */
	NOISE_AUTHTAG_LEN = CHACHA20POLY1305_AUTHTAG_SIZE,
	
	/* BLAKE2s 哈希输出长度 (32字节)
	 * 用于：密钥派生、消息认证、协议状态哈希 */
	NOISE_HASH_LEN = BLAKE2S_HASH_SIZE
};

/**
 * noise_encrypted_len - 计算 AEAD 加密后的数据长度
 * @plain_len: 明文数据长度
 * 
 * AEAD 加密开销：
 * ┌─────────────────┐    ┌─────────────────┐    ┌─────────────────┐
 * │   明文数据       │───►│   ChaCha20      │───►│  密文 + 认证标签 │
 * │  (plain_len)    │    │   加密          │    │ (plain_len+16)  │
 * └─────────────────┘    └─────────────────┘    └─────────────────┘
 *         │                      │                       │
 *    原始数据大小          AEAD加密算法           密文数据 + MAC标签
 * 
 * 返回值：加密后的总长度（明文长度 + 16字节认证标签）
 */
#define noise_encrypted_len(plain_len) ((plain_len) + NOISE_AUTHTAG_LEN)

