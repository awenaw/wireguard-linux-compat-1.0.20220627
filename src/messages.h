/**
 * counter_values - 重放攻击防护的计数器窗口参数
 * 
 * 重放攻击防护原理：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                    计数器滑动窗口机制                         │
 * │                                                             │
 * │  旧消息 ←─────────── 当前位置 ───────────→ 未来消息           │
 * │    ↓                   ↓                    ↓              │
 * │ [拒绝]            [检查位图]              [接受]             │
 * │                                                             │
 * │ ┌─────────────────┐ ┌─────────────────┐ ┌─────────────────┐ │
 * │ │   已处理消息     │ │   滑动窗口      │ │   未来消息      │ │
 * │ │  (自动拒绝)     │ │ (位图检查重放)   │ │  (直接接受)    │ │
 * │ └─────────────────┘ └─────────────────┘ └─────────────────┘ │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 位图实现细节：
 * 
 * 计数器空间分配：
 * ┌──────────────────┬────────────────────┬──────────────────┐
 * │   冗余位 (64位)   │    窗口位图         │   未来空间       │
 * │  (平台相关)      │   (8128位)         │   (无限制)       │
 * └──────────────────┴────────────────────┴──────────────────┘
 *         │                     │                    │
 *    避免边界检查           实际重放检查         接受新消息
 * 
 * 工作机制：
 * 1. 每个数据包都有64位单调递增计数器
 * 2. 维护8192位的滑动窗口位图
 * 3. 超前消息直接接受，更新窗口位置
 * 4. 窗口内消息检查对应位，已收到则拒绝
 * 5. 窗口外旧消息直接拒绝
 * 
 * 安全保证：
 * • 防重放：相同计数器的消息只处理一次
 * • 乱序处理：允许一定范围内的消息乱序
 * • 高效检查：O(1)时间复杂度的重放检测
 * • 内存高效：固定大小的位图结构
 */
enum counter_values {
	/* 计数器位图总位数 (8192位 = 1024字节)
	 * 这个大小提供了足够大的窗口来处理网络乱序，
	 * 同时保持合理的内存使用量 */
	COUNTER_BITS_TOTAL = 8192,
	
	/* 冗余位数 (64位，平台相关)
	 * 这些额外的位用于避免边界条件检查，
	 * 简化实现并提高性能 */
	COUNTER_REDUNDANT_BITS = BITS_PER_LONG,
	
	/* 实际滑动窗口大小 (8128位)
	 * 这是用于重放检测的有效窗口大小，
	 * 支持在此范围内的消息乱序接收 */
	COUNTER_WINDOW_SIZE = COUNTER_BITS_TOTAL - COUNTER_REDUNDANT_BITS
};

