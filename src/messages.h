/*
 * =============================================================================
 *                        WireGuard 协议消息格式定义
 * =============================================================================
 * 
 * 本文件定义了 WireGuard 协议的所有消息类型、数据结构和相关常数。
 * WireGuard 使用基于 Noise 协议框架的自定义消息格式，提供强加密和前向保密。
 * 
 * 协议概览：
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                        WireGuard 协议栈                          │
 * ├─────────────────────────────────────────────────────────────────┤
 * │  应用层数据 (IP数据包)                                           │
 * ├─────────────────────────────────────────────────────────────────┤
 * │  WireGuard 数据消息 (ChaCha20Poly1305 加密)                     │
 * ├─────────────────────────────────────────────────────────────────┤
 * │  WireGuard 握手消息 (Noise_IK 握手模式)                         │
 * ├─────────────────────────────────────────────────────────────────┤
 * │  UDP 传输层                                                      │
 * ├─────────────────────────────────────────────────────────────────┤
 * │  IP 网络层                                                       │
 * └─────────────────────────────────────────────────────────────────┘
 * 
 * 消息类型分层：
 * 
 * 1. 握手消息层 (Handshake Messages):
 *    ┌─────────────────┐    ┌─────────────────┐    ┌─────────────────┐
 *    │ Initiation (1)  │───►│  Response (2)   │───►│   Cookie (3)    │
 *    │ 发起握手请求     │    │  响应握手请求    │    │ DoS防护Cookie   │
 *    └─────────────────┘    └─────────────────┘    └─────────────────┘
 *           │                       │                       │
 *      包含发起者公钥          包含响应者公钥         包含防DoS令牌
 *      和加密的时间戳          和确认信息             和nonce
 * 
 * 2. 数据消息层 (Data Messages):
 *    ┌─────────────────────────────────────────────────────────────┐
 *    │                    Data Message (4)                         │
 *    │  ┌─────────────┐ ┌─────────────┐ ┌─────────────────────────┐ │
 *    │  │   Header    │ │ Key Index   │ │   Encrypted Payload     │ │
 *    │  │   (4字节)    │ │  (4字节)    │ │  (变长,ChaCha20Poly1305) │ │
 *    │  └─────────────┘ └─────────────┘ └─────────────────────────┘ │
 *    └─────────────────────────────────────────────────────────────┘
 * 
 * 加密算法组合：
 * • Curve25519：ECDH 密钥交换
 * • ChaCha20Poly1305：AEAD 对称加密
 * • BLAKE2s：加密哈希函数
 * • HKDF：密钥派生函数
 * 
 * 安全特性：
 * • 前向保密：每次握手生成新的临时密钥
 * • 身份隐藏：静态密钥被加密保护
 * • 重放保护：单调递增的计数器
 * • DoS防护：Cookie机制防止资源耗尽
 * • 时序保护：常量时间算法实现
 * 
 * 性能优化：
 * • 最小消息开销：紧凑的二进制格式
 * • 高效加密：现代AEAD算法
 * • 批量处理：支持数据包批处理
 * • 内存对齐：优化的结构体布局
 * =============================================================================
 */

