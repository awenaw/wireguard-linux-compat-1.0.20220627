/**
 * cookie_values - Cookie 防 DoS 攻击机制的参数定义
 * 
 * Cookie 防护工作原理：
 * ┌─────────────────┐    ┌─────────────────┐    ┌─────────────────┐
 * │   正常握手      │    │   负载过高      │    │  Cookie 防护    │
 * │                 │───►│                 │───►│                 │
 * │ Client ────────►│    │ 大量握手请求    │    │ Server 要求     │
 * │ Server         │    │ 服务器压力大    │    │ Cookie 验证     │
 * └─────────────────┘    └─────────────────┘    └─────────────────┘
 *         │                      │                      │
 *    直接处理握手            检测到攻击              要求客户端证明
 * 
 * Cookie 机制时序：
 * 1. 服务器检测到负载过高 (根据 CPU 使用率)
 * 2. 开始要求所有新握手提供有效的 Cookie
 * 3. 客户端必须先请求 Cookie，再发起握手
 * 4. 无效或过期的 Cookie 会被拒绝
 * 
 * 这种机制有效防止：
 * • 握手洪水攻击 (Handshake flood)
 * • CPU 耗尽攻击 (CPU exhaustion)
 * • 内存耗尽攻击 (Memory exhaustion)
 */
enum cookie_values {
	/* Cookie 密钥最大有效期 (120秒)
	 * 服务器定期更换用于生成 Cookie 的密钥，
	 * 防止攻击者长期重用相同的 Cookie */
	COOKIE_SECRET_MAX_AGE = 2 * 60,
	
	/* Cookie 密钥延迟容忍 (5秒)
	 * 在密钥轮换期间，同时接受新旧两个密钥生成的 Cookie，
	 * 避免网络延迟导致的合法 Cookie 被误拒 */
	COOKIE_SECRET_LATENCY = 5,
	
	/* Cookie 随机数长度 (24字节)
	 * 使用 XChaCha20Poly1305 的 nonce 长度，
	 * 确保每个 Cookie 都有唯一的随机数 */
	COOKIE_NONCE_LEN = XCHACHA20POLY1305_NONCE_SIZE,
	
	/* Cookie 数据长度 (16字节)
	 * 足够的熵值来确保安全性，
	 * 同时保持消息的紧凑性 */
	COOKIE_LEN = 16
};

