/**
 * message_type - WireGuard 协议支持的消息类型
 * 
 * 完整的握手和数据传输流程：
 * 
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                       WireGuard 协议交互流程                      │
 * │                                                                 │
 * │  发起方 (Initiator)           网络          响应方 (Responder) │
 * │        │                                              │        │
 * │        │  1. Handshake Initiation (1)                │        │
 * │        │ ─────────────────────────────────────────────►        │
 * │        │    • 发起方的临时公钥                          │        │
 * │        │    • 加密的静态公钥                            │        │
 * │        │    • 加密的时间戳                              │        │
 * │        │                                              │        │
 * │        │  2. Handshake Response (2)                  │        │
 * │        │ ◄─────────────────────────────────────────────        │
 * │        │    • 响应方的临时公钥                          │        │
 * │        │    • 会话索引映射                              │        │
 * │        │    • 空的加密载荷(确认)                        │        │
 * │        │                                              │        │
 * │    [可选 DoS 防护流程]                                 │        │
 * │        │  3. Cookie Request/Response (3)             │        │
 * │        │ ◄─────────────────────────────────────────────        │
 * │        │    • 防 DoS 的 Cookie 令牌                    │        │
 * │        │    • 高负载时需要                              │        │
 * │        │                                              │        │
 * │    [握手完成，建立加密通道]                             │        │
 * │        │                                              │        │
 * │        │  4. Data Messages (4) ←→                    │        │
 * │        │ ◄─────────────────────────────────────────────        │
 * │        │    • 加密的IP数据包                            │        │
 * │        │    • 单调递增计数器                            │        │
 * │        │    • 高效的AEAD加密                           │        │
 * │        │                                              │        │
 * └─────────────────────────────────────────────────────────────────┘
 */
enum message_type {
	/* 无效消息类型 (0)
	 * 用途：
	 * • 错误检测：识别损坏或未知的消息
	 * • 协议兼容性：未来版本的消息类型识别
	 * • 调试支持：清晰标识无效数据包 */
	MESSAGE_INVALID = 0,
	
	/* 握手发起消息 (1)
	 * 发送方：想要建立连接的一方 (Initiator)
	 * 
	 * 包含内容：
	 * • sender_index：发起方分配的会话索引
	 * • ephemeral：发起方的临时公钥 (未加密)
	 * • static：发起方的静态公钥 (加密保护身份隐私)
	 * • timestamp：当前时间戳 (加密，用于重放保护)
	 * • macs：消息认证码 (防篡改，可选Cookie支持)
	 * 
	 * 安全特性：
	 * - 身份保护：静态公钥被加密，攻击者无法识别身份
	 * - 前向保密：使用临时密钥，即使长期密钥泄露也不影响历史会话
	 * - 重放保护：时间戳防止重放攻击
	 * - 完整性保护：MAC确保消息未被篡改 */
	MESSAGE_HANDSHAKE_INITIATION = 1,
	
	/* 握手响应消息 (2) 
	 * 发送方：响应连接请求的一方 (Responder)
	 * 
	 * 包含内容：
	 * • sender_index：响应方分配的会话索引
	 * • receiver_index：对应的发起方索引 (建立双向映射)
	 * • ephemeral：响应方的临时公钥 (未加密)
	 * • empty：空的加密载荷 (仅用于确认和MAC验证)
	 * • macs：消息认证码
	 * 
	 * 协议意义：
	 * - 确认握手：表明响应方已收到并处理发起消息
	 * - 建立会话：双方现在都有对方的临时公钥
	 * - 索引关联：建立双向的会话索引映射关系
	 * - 密钥派生：双方可以推导出相同的会话密钥 */
	MESSAGE_HANDSHAKE_RESPONSE = 2,
	
	/* Cookie 消息 (3)
	 * 发送方：正在承受DoS攻击压力的服务器
	 * 
	 * 包含内容：
	 * • receiver_index：目标会话索引
	 * • nonce：Cookie加密使用的随机数
	 * • cookie：加密的Cookie数据 (包含客户端IP等信息)
	 * 
	 * DoS 防护机制：
	 * - 服务器在高负载时发送此消息而不是直接处理握手
	 * - 客户端必须在后续握手中包含有效的Cookie
	 * - Cookie绑定客户端IP，防止IP伪造攻击
	 * - 有时间限制，防止Cookie重用攻击 */
	MESSAGE_HANDSHAKE_COOKIE = 3,
	
	/* 数据传输消息 (4)
	 * 发送方：握手完成后的任意一方
	 * 
	 * 包含内容：
	 * • key_idx：密钥索引 (指向特定的密钥对)
	 * • counter：单调递增的包计数器 (重放保护)
	 * • data：ChaCha20Poly1305加密的IP数据包
	 * 
	 * 性能特点：
	 * - 最小开销：仅16字节头部 + 16字节MAC
	 * - 高速加密：ChaCha20Poly1305适合高速网络
	 * - 硬件支持：现代CPU有专门的加速指令
	 * - 批量处理：支持高效的数据包批处理
	 * 
	 * 安全保证：
	 * - 完美前向保密：定期更新会话密钥
	 * - 重放防护：严格的计数器检查
	 * - 完整性验证：Poly1305确保数据未被篡改
	 * - 保密性：ChaCha20确保数据不被窃听 */
	MESSAGE_DATA = 4
};

