/**
 * SKB_HEADER_LEN - 网络栈头部空间计算
 * 
 * 网络协议栈头部空间需求：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                 Linux 网络栈头部分层                         │
 * │                                                             │
 * │ ┌─────────────┐  ┌─────────────┐  ┌─────────────┐          │
 * │ │  NET_SKB_   │  │    UDP      │  │ IP Header   │          │
 * │ │    PAD      │  │   Header    │  │(IPv4/IPv6)  │          │
 * │ │            │  │             │  │            │          │
 * │ │ • 对齐填充   │  │ • 源端口     │  │ • 版本信息   │          │
 * │ │ • 平台相关   │  │ • 目标端口   │  │ • 地址信息   │          │
 * │ │ • DMA要求   │  │ • 长度字段   │  │ • 路由信息   │          │
 * │ └─────────────┘  └─────────────┘  └─────────────┘          │
 * │      变长           8字节         20/40字节                 │
 * └─────────────────────────────────────────────────────────────┘
 */
#define SKB_HEADER_LEN                                       \
	(max(sizeof(struct iphdr), sizeof(struct ipv6hdr)) + \
	 sizeof(struct udphdr) + NET_SKB_PAD)

/**
 * DATA_PACKET_HEAD_ROOM - 数据包头部预留空间
 * 
 * 缓冲区头部空间布局：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                   sk_buff 头部空间                          │
 * │                                                             │
 * │ ┌─────────────────┐  ┌─────────────────┐                   │
 * │ │  WireGuard      │  │   Network       │                   │
 * │ │   Message       │  │   Headers       │                   │
 * │ │   Header        │  │                │                   │
 * │ │                │  │ • IP Header     │                   │
 * │ │ • Type(4)       │  │ • UDP Header    │                   │
 * │ │ • Key_idx(4)    │  │ • Padding       │                   │
 * │ │ • Counter(8)    │  │                │                   │
 * │ └─────────────────┘  └─────────────────┘                   │
 * │      16字节           SKB_HEADER_LEN                       │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 4字节对齐：
 * • ALIGN(size, 4)：确保总大小是4的倍数
 * • 32位架构友好：避免未对齐的内存访问
 * • 性能优化：减少内存访问周期
 */
#define DATA_PACKET_HEAD_ROOM \
	ALIGN(sizeof(struct message_data) + SKB_HEADER_LEN, 4)

