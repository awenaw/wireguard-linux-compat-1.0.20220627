/**
 * message_header - 所有 WireGuard 消息的通用头部
 * 
 * 头部格式优化说明：
 * 
 * 理想的内存布局：
 * ┌─────────────┬─────────────┬─────────────┬─────────────┐
 * │   消息类型   │   保留字节   │   保留字节   │   保留字节   │
 * │  u8 type    │ u8 zero[0]  │ u8 zero[1]  │ u8 zero[2]  │
 * │   1字节     │    1字节    │    1字节    │    1字节    │
 * └─────────────┴─────────────┴─────────────┴─────────────┘
 * 
 * 实际实现 (小端序优化)：
 * ┌─────────────────────────────────────────────────────────┐
 * │                   __le32 type                          │
 * │  ┌─────────────┬─────────────┬─────────────┬─────────────┐ │
 * │  │ 消息类型[0] │     0[1]    │     0[2]    │     0[3]    │ │
 * │  │   1字节     │    1字节    │    1字节    │    1字节    │ │
 * │  └─────────────┴─────────────┴─────────────┴─────────────┘ │
 * └─────────────────────────────────────────────────────────┘
 * 
 * 这种设计的优势：
 * 1. 性能优化：
 *    • 单次32位读取 vs 4次8位读取
 *    • CPU缓存友好：对齐到4字节边界
 *    • 现代处理器优化：32位操作通常比8位更高效
 * 
 * 2. 类型检查简化：
 *    • if (header->type == cpu_to_le32(MESSAGE_DATA))
 *    • 编译器可以优化为直接的32位比较
 *    • 减少字节序转换开销
 * 
 * 3. 协议扩展性：
 *    • 保留3字节用于未来的功能扩展
 *    • 保持4字节对齐，便于后续字段布局
 *    • 版本控制和标志位的预留空间
 * 
 * 4. 网络字节序处理：
 *    • 统一的小端序格式
 *    • 跨平台兼容性保证
 *    • 减少字节序转换错误
 */
struct message_header {
	/* 消息类型 (小端序32位整数)
	 * 
	 * 实际使用中：
	 * • 只有最低字节包含类型信息 (1-4)
	 * • 高3字节必须为0，用于协议完整性检查
	 * • 可以通过单次比较验证消息类型和保留字段
	 * 
	 * 类型映射：
	 * - 1 = MESSAGE_HANDSHAKE_INITIATION
	 * - 2 = MESSAGE_HANDSHAKE_RESPONSE  
	 * - 3 = MESSAGE_HANDSHAKE_COOKIE
	 * - 4 = MESSAGE_DATA
	 * - 其他值 = MESSAGE_INVALID
	 */
	__le32 type;
};

/**
 * message_macs - 消息认证码对 (MAC1 + MAC2)
 * 
 * 双层MAC验证机制：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                     双重认证保护                             │
 * │                                                             │
 * │  ┌─────────────────┐              ┌─────────────────┐       │
 * │  │     MAC1        │              │     MAC2        │       │
 * │  │  (基础认证)      │    +         │ (Cookie认证)     │       │
 * │  │                 │              │                 │       │
 * │  │ • 静态密钥计算   │              │ • Cookie验证     │       │
 * │  │ • 消息完整性     │              │ • DoS防护       │       │
 * │  │ • 身份验证      │              │ • 负载控制       │       │
 * │  └─────────────────┘              └─────────────────┘       │
 * │           │                              │                 │
 * │      总是存在                     仅在需要时使用              │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * MAC1 计算方法：
 * • 输入：整个消息内容 (除了MAC字段本身)
 * • 密钥：BLAKE2s(label || 对端静态公钥)
 * • 算法：BLAKE2s MAC
 * • 目的：验证消息完整性和发送者身份
 * 
 * MAC2 使用场景：
 * • 正常情况：全零，不使用
 * • DoS防护：包含基于Cookie的MAC
 * • 计算：BLAKE2s(消息 || Cookie)
 * • 验证：服务器检查Cookie有效性
 */
struct message_macs {
	/* MAC1: 基础消息认证码 (16字节)
	 * 用途：
	 * • 验证消息完整性：确保传输中未被篡改
	 * • 身份认证：证明发送者拥有对应的私钥
	 * • 协议完整性：所有握手消息都必须有效的MAC1
	 * 
	 * 安全属性：
	 * - 防篡改：任何修改都会导致MAC验证失败
	 * - 防伪造：没有私钥无法生成有效MAC
	 * - 重放检测：配合时间戳提供重放保护 */
	u8 mac1[COOKIE_LEN];
	
	/* MAC2: Cookie认证码 (16字节)  
	 * 用途：
	 * • DoS防护：证明客户端获得了有效的Cookie
	 * • 负载控制：服务器可以选择性处理握手请求
	 * • IP验证：Cookie绑定客户端IP地址
	 * 
	 * 状态：
	 * - 正常情况：全零 (0x00 * 16)
	 * - 高负载时：包含有效的Cookie MAC
	 * - 验证失败：握手被拒绝 */
	u8 mac2[COOKIE_LEN];
};

/**
 * message_handshake_initiation - 握手发起消息 (消息类型1)
 * 
 * 消息结构布局：
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                握手发起消息 (148 字节)                            │
 * ├───────────────┬─────────┬───────────────────────────────────────┤
 * │   字段名称     │  大小   │              描述                     │
 * ├───────────────┼─────────┼───────────────────────────────────────┤
 * │ header        │  4字节  │ 消息类型 = 1                         │
 * │ sender_index  │  4字节  │ 发起方会话索引                       │
 * │ ephemeral     │ 32字节  │ 发起方临时公钥 (未加密)               │
 * │ static        │ 48字节  │ 发起方静态公钥 (加密+MAC,32+16)       │
 * │ timestamp     │ 28字节  │ 当前时间戳 (加密+MAC,12+16)          │
 * │ macs          │ 32字节  │ MAC1(16) + MAC2(16)                  │
 * └───────────────┴─────────┴───────────────────────────────────────┘
 * 
 * Noise_IK 握手模式 - 第一步：
 * ┌─────────────────────────────────────────────────────────────┐
 * │  发起方 (Initiator)                响应方 (Responder)       │
 * │                                                             │
 * │  已知: R静态公钥               已知: R静态私钥, I静态公钥     │
 * │  生成: I临时密钥对             等待: 握手发起消息             │
 * │                                                             │
 * │  ┌─────────────────┐         ┌─────────────────┐           │
 * │  │  准备发送数据:   │  ────► │   验证接收:     │           │
 * │  │                │         │                │           │
 * │  │ • 临时公钥 (明文) │         │ • 临时公钥提取  │           │
 * │  │ • 静态公钥 (密文) │         │ • 静态公钥解密  │           │
 * │  │ • 时间戳 (密文)  │         │ • 时间戳验证    │           │
 * │  │ • MAC验证码     │         │ • MAC完整性检查 │           │
 * │  └─────────────────┘         └─────────────────┘           │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 安全分析：
 * 1. 身份保护：静态公钥被加密，被动观察者无法识别发起方身份
 * 2. 前向保密：临时密钥确保即使静态密钥泄露，历史会话仍安全
 * 3. 重放保护：时间戳防止旧消息被恶意重放
 * 4. 完整性保护：MAC确保消息在传输中未被修改
 */
struct message_handshake_initiation {
	/* 消息头部 (4字节)
	 * 包含消息类型 = MESSAGE_HANDSHAKE_INITIATION (1) */
	struct message_header header;
	
	/* 发起方会话索引 (4字节，小端序)
	 * 用途：
	 * • 会话标识：发起方为此握手分配的唯一标识符
	 * • 状态查找：响应方使用此索引查找握手状态
	 * • 索引管理：必须是随机生成，防止猜测攻击
	 * • 生命周期：在整个握手过程中保持不变 */
	__le32 sender_index;
	
	/* 发起方临时公钥 (32字节，未加密)
	 * 密码学作用：
	 * • DH密钥交换：与响应方的临时/静态密钥进行交换
	 * • 前向保密：每次握手都生成新的临时密钥对
	 * • Noise协议：Curve25519 椭圆曲线公钥
	 * • 可见性：明文传输，攻击者可以观察但无法利用 */
	u8 unencrypted_ephemeral[NOISE_PUBLIC_KEY_LEN];
	
	/* 发起方静态公钥 (48字节：32字节数据 + 16字节MAC)
	 * 加密保护：
	 * • 算法：ChaCha20Poly1305 AEAD
	 * • 密钥：DH(I临时私钥, R静态公钥) 派生的加密密钥
	 * • 目的：隐藏发起方身份，防止身份关联攻击
	 * • 验证：响应方解密后验证是否为已知的对等体 */
	u8 encrypted_static[noise_encrypted_len(NOISE_PUBLIC_KEY_LEN)];
	
	/* 加密的时间戳 (28字节：12字节时间戳 + 16字节MAC)
	 * 时间戳结构：
	 * • 8字节：Unix时间戳 (秒)
	 * • 4字节：毫秒部分
	 * 
	 * 安全功能：
	 * • 重放保护：防止旧握手消息被重新发送
	 * • 时钟偏差：允许合理的时间差 (几分钟内)
	 * • 加密保护：防止时间信息泄露
	 * • DoS防护：过期消息直接丢弃，节省处理资源 */
	u8 encrypted_timestamp[noise_encrypted_len(NOISE_TIMESTAMP_LEN)];
	
	/* 消息认证码对 (32字节) */
	struct message_macs macs;
};

/**
 * message_handshake_response - 握手响应消息 (消息类型2)
 * 
 * 消息结构布局：
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                握手响应消息 (92 字节)                             │
 * ├───────────────┬─────────┬───────────────────────────────────────┤
 * │   字段名称     │  大小   │              描述                     │
 * ├───────────────┼─────────┼───────────────────────────────────────┤
 * │ header        │  4字节  │ 消息类型 = 2                         │
 * │ sender_index  │  4字节  │ 响应方会话索引                       │
 * │ receiver_index│  4字节  │ 对应的发起方索引                     │
 * │ ephemeral     │ 32字节  │ 响应方临时公钥 (未加密)               │
 * │ nothing       │ 16字节  │ 空载荷 (仅MAC,0+16)                  │
 * │ macs          │ 32字节  │ MAC1(16) + MAC2(16)                  │
 * └───────────────┴─────────┴───────────────────────────────────────┘
 * 
 * Noise_IK 握手模式 - 第二步：
 * ┌─────────────────────────────────────────────────────────────┐
 * │  响应方 (Responder)                发起方 (Initiator)       │
 * │                                                             │
 * │  已处理: 发起消息              等待: 响应消息                 │
 * │  验证: I静态公钥,时间戳         准备: 建立数据传输会话         │
 * │  生成: R临时密钥对             验证: R临时公钥,索引映射       │
 * │                                                             │
 * │  ┌─────────────────┐         ┌─────────────────┐           │
 * │  │  响应发送数据:   │  ────► │   确认接收:     │           │
 * │  │                │         │                │           │
 * │  │ • R临时公钥     │         │ • 提取R临时公钥  │           │
 * │  │ • R会话索引     │         │ • 建立索引映射   │           │
 * │  │ • I会话索引     │         │ • 验证MAC完整性  │           │
 * │  │ • 空载荷+MAC    │         │ • 派生传输密钥   │           │
 * │  └─────────────────┘         └─────────────────┘           │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 密钥派生完成：
 * 此时双方都拥有了所有必要的密钥材料，可以派生出传输密钥：
 * • DH1 = DH(I临时, R静态)  [发起消息中使用]
 * • DH2 = DH(I静态, R静态)  [发起消息中使用]  
 * • DH3 = DH(I临时, R临时)  [响应消息后可计算]
 * • 传输密钥 = HKDF(DH1, DH2, DH3, ...)
 */
struct message_handshake_response {
	/* 消息头部 (4字节)
	 * 包含消息类型 = MESSAGE_HANDSHAKE_RESPONSE (2) */
	struct message_header header;
	
	/* 响应方会话索引 (4字节，小端序)
	 * 用途：
	 * • 新索引分配：响应方为这个握手会话分配的索引
	 * • 双向映射：与发起方索引建立对应关系
	 * • 数据传输：后续数据包将使用此索引标识会话
	 * • 查找优化：接收方快速定位对应的密钥和状态 */
	__le32 sender_index;
	
	/* 接收方索引 (4字节，小端序)
	 * 含义：
	 * • 索引确认：必须与发起消息中的sender_index相同
	 * • 会话关联：建立双方索引的双向映射关系
	 * • 错误检测：不匹配的索引表明消息错误或攻击
	 * • 状态同步：确保双方对会话状态的理解一致 */
	__le32 receiver_index;
	
	/* 响应方临时公钥 (32字节，未加密)
	 * 密码学作用：
	 * • DH交换完成：现在双方都有对方的临时公钥
	 * • 密钥派生：计算 DH(I临时, R临时) 完成所有DH交换
	 * • 前向保密：每次握手的临时密钥都是唯一的
	 * • 传输准备：为数据传输阶段准备会话密钥 */
	u8 unencrypted_ephemeral[NOISE_PUBLIC_KEY_LEN];
	
	/* 加密的空载荷 (16字节：0字节数据 + 16字节MAC)
	 * 设计原因：
	 * • 协议完整性：Noise协议要求此处有加密载荷
	 * • MAC验证：证明响应方正确处理了握手状态
	 * • 密钥确认：隐式确认双方派生了相同的密钥
	 * • 攻击防护：防止某些类型的握手操控攻击
	 * 
	 * 实现细节：
	 * - 输入：0字节的空数据
	 * - 加密：使用握手阶段派生的密钥
	 * - 输出：仅包含16字节的Poly1305 MAC标签
	 * - 验证：发起方必须能成功验证此MAC */
	u8 encrypted_nothing[noise_encrypted_len(0)];
	
	/* 消息认证码对 (32字节) */
	struct message_macs macs;
};

/**
 * message_handshake_cookie - Cookie 防DoS消息 (消息类型3)
 * 
 * 消息结构布局：
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                   Cookie 消息 (64 字节)                          │
 * ├───────────────┬─────────┬───────────────────────────────────────┤
 * │   字段名称     │  大小   │              描述                     │
 * ├───────────────┼─────────┼───────────────────────────────────────┤
 * │ header        │  4字节  │ 消息类型 = 3                         │
 * │ receiver_index│  4字节  │ 目标会话索引                         │
 * │ nonce         │ 24字节  │ XChaCha20Poly1305 随机数             │
 * │ cookie        │ 32字节  │ 加密的Cookie (16+16)                 │
 * └───────────────┴─────────┴───────────────────────────────────────┘
 * 
 * DoS 防护工作流程：
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                      Cookie 防护机制                            │
 * │                                                                 │
 * │  客户端                服务器                    攻击者          │
 * │     │                    │                        │            │
 * │     │   握手请求          │                        │            │
 * │     │ ──────────────────► │                        │            │
 * │     │                    │ [检测负载过高]          │            │
 * │     │                    │                        │            │
 * │     │   Cookie 消息       │                        │            │
 * │     │ ◄────────────────── │                        │            │
 * │     │                    │                        │            │
 * │     │ 握手请求+Cookie     │                        │            │
 * │     │ ──────────────────► │                        │            │
 * │     │   [验证通过]        │                        │            │
 * │     │                    │                        │            │
 * │     │                    │   握手洪水攻击 ───────► │            │
 * │     │                    │   [需要Cookie] ◄─────── │            │
 * │     │                    │   [无法获得Cookie] ──► │            │
 * │     │                    │   [攻击被阻止]         │            │
 * └─────────────────────────────────────────────────────────────────┘
 * 
 * Cookie 安全机制：
 * 1. IP 地址绑定：Cookie 包含客户端的 IP 地址信息
 * 2. 时间限制：Cookie 有有效期，防止重用攻击  
 * 3. 密钥轮换：服务器定期更换 Cookie 生成密钥
 * 4. 随机化：每个 Cookie 都有唯一的随机数
 */
struct message_handshake_cookie {
	/* 消息头部 (4字节)
	 * 包含消息类型 = MESSAGE_HANDSHAKE_COOKIE (3) */
	struct message_header header;
	
	/* 接收方索引 (4字节，小端序)
	 * 用途：
	 * • 会话关联：指向需要Cookie验证的握手会话
	 * • 索引匹配：必须与之前握手请求中的发起方索引相同
	 * • 状态查找：客户端用此索引找到对应的握手状态
	 * • 错误处理：索引不匹配表明消息错误或网络问题 */
	__le32 receiver_index;
	
	/* Cookie加密随机数 (24字节)
	 * XChaCha20Poly1305 算法规格：
	 * • 长度：24字节 (192位) 随机数
	 * • 用途：确保每个Cookie加密都是唯一的
	 * • 安全性：足够的熵防止随机数重复使用
	 * • 传输：明文发送，接收方需要用于解密Cookie
	 * 
	 * 为什么使用XChaCha20而非ChaCha20：
	 * - 更长的nonce：24字节vs12字节，降低碰撞风险
	 * - 更高的安全边界：适合大规模Cookie生成
	 * - 简化实现：无需复杂的nonce管理机制 */
	u8 nonce[COOKIE_NONCE_LEN];
	
	/* 加密的Cookie数据 (32字节：16字节Cookie + 16字节MAC)
	 * Cookie内容结构：
	 * • 客户端IP地址 (4或16字节，取决于IPv4/IPv6)
	 * • 时间戳 (8字节)
	 * • 随机填充 (补足到16字节)
	 * 
	 * 加密保护：
	 * • 算法：XChaCha20Poly1305 AEAD
	 * • 密钥：服务器的Cookie密钥 (定期轮换)
	 * • 随机数：上述nonce字段
	 * • 完整性：Poly1305 MAC防止篡改
	 * 
	 * 验证过程：
	 * 1. 客户端收到Cookie后存储
	 * 2. 后续握手请求在MAC2中包含基于Cookie的MAC
	 * 3. 服务器验证MAC2以确认Cookie有效性
	 * 4. 通过验证后处理握手，否则丢弃 */
	u8 encrypted_cookie[noise_encrypted_len(COOKIE_LEN)];
};

/**
 * message_data - 数据传输消息 (消息类型4)
 * 
 * 消息结构布局：
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                数据传输消息 (变长)                                │
 * ├───────────────┬─────────┬───────────────────────────────────────┤
 * │   字段名称     │  大小   │              描述                     │
 * ├───────────────┼─────────┼───────────────────────────────────────┤
 * │ header        │  4字节  │ 消息类型 = 4                         │
 * │ key_idx       │  4字节  │ 密钥对索引                           │
 * │ counter       │  8字节  │ 数据包计数器                         │
 * │ encrypted_data│ 变长    │ 加密的IP数据包+MAC                   │
 * └───────────────┴─────────┴───────────────────────────────────────┘
 * 
 * 数据传输流程：
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                    高效数据传输                                  │
 * │                                                                 │
 * │  发送方                                          接收方          │
 * │     │                                              │            │
 * │ ┌─────────────────┐                      ┌─────────────────┐   │
 * │ │ 1. IP 数据包    │                      │ 4. 解密验证      │   │
 * │ │   准备发送      │                      │   提取IP包       │   │
 * │ └─────────────────┘                      └─────────────────┘   │
 * │     │                                              ▲            │
 * │     ▼                                              │            │
 * │ ┌─────────────────┐    WireGuard消息     ┌─────────────────┐   │
 * │ │ 2. 加密打包     │ ──────────────────► │ 3. 索引查找     │   │
 * │ │ • 查找密钥对     │                      │ • 找到密钥对     │   │
 * │ │ • 计数器递增     │                      │ • 重放检测      │   │
 * │ │ • AEAD加密      │                      │ • 计数器验证     │   │
 * │ └─────────────────┘                      └─────────────────┘   │
 * └─────────────────────────────────────────────────────────────────┘
 * 
 * 性能优化设计：
 * • 最小头部：仅16字节固定头部 + 16字节MAC = 32字节开销
 * • 零拷贝：encrypted_data 使用柔性数组，支持就地加密/解密
 * • 批量处理：支持网络栈的批量数据包处理机制
 * • 硬件加速：ChaCha20Poly1305 在现代CPU上有专门指令支持
 */
struct message_data {
	/* 消息头部 (4字节)
	 * 包含消息类型 = MESSAGE_DATA (4) */
	struct message_header header;
	
	/* 密钥对索引 (4字节，小端序)
	 * 索引查找机制：
	 * • 快速查找：接收方用此索引在索引哈希表中查找密钥对
	 * • 会话识别：标识这个数据包属于哪个加密会话
	 * • 密钥轮换：新旧密钥对可能同时存在，通过索引区分
	 * • 性能优化：O(1)查找时间，无需遍历所有会话
	 * 
	 * 索引生命周期：
	 * - 握手完成时分配 (随机生成)
	 * - 密钥过期时回收
	 * - 与 peerlookup.c 中的索引管理机制配合使用 */
	__le32 key_idx;
	
	/* 数据包计数器 (8字节，小端序)
	 * 重放防护机制：
	 * • 单调递增：发送方严格递增此计数器
	 * • 重放检测：接收方维护滑动窗口位图检查重复
	 * • 乱序处理：允许一定范围内的包乱序到达
	 * • 溢出保护：接近2^64时强制重新握手
	 * 
	 * 实现细节：
	 * - 每个密钥对维护独立的计数器
	 * - 发送时原子递增，确保唯一性
	 * - 接收时与滑动窗口算法配合 (见counter_values)
	 * - 为AEAD提供必要的nonce唯一性保证 */
	__le64 counter;
	
	/* 加密的数据载荷 (变长，柔性数组)
	 * ChaCha20Poly1305 AEAD 加密：
	 * 
	 * 输入处理：
	 * • 明文：原始IP数据包 (IPv4/IPv6)
	 * • 关联数据：消息头部 (header + key_idx + counter)
	 * • 密钥：通过索引查找的传输密钥
	 * • Nonce：由计数器和密钥派生
	 * 
	 * 输出格式：
	 * • 密文：加密后的IP数据包 (与明文同长度)
	 * • MAC标签：16字节Poly1305认证标签
	 * • 总长度：明文长度 + 16字节
	 * 
	 * 安全保证：
	 * - 保密性：ChaCha20确保数据内容不被窃听
	 * - 完整性：Poly1305确保数据和头部未被篡改
	 * - 认证性：只有拥有正确密钥的对等体能生成有效数据
	 * - 前向保密：定期密钥轮换确保长期安全性 */
	u8 encrypted_data[];
};

