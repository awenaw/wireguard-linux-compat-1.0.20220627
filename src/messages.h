/**
 * HANDSHAKE_DSCP - 握手消息的 DSCP 标记
 * 
 * DSCP 值分解：0x88 = 10001000 (二进制)
 * ┌─────────────────────────────────────────────────────────────┐
 * │                    DSCP 字段解析                            │
 * │                                                             │
 * │  7    6    5    4    3    2    1    0   (位位置)             │
 * │ ┌────┬────┬────┬────┬────┬────┬────┬────┐                   │
 * │ │ 1  │ 0  │ 0  │ 0  │ 1  │ 0  │ 0  │ 0  │                   │
 * │ └────┴────┴────┴────┴────┴────┴────┴────┘                   │
 * │  │              │              │       │                    │
 * │  └──────────────┼──────────────┘       └── ECN = 00         │
 * │              DSCP = AF41                  (无拥塞通知)        │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * AF41 (Assured Forwarding 41) 特性：
 * • 优先级：高优先级流量类别 (Class 4)
 * • 丢包优先级：低丢包概率 (Drop Precedence 1)
 * • 用途：重要的交互式应用，如VPN控制流量
 * • 网络处理：路由器会优先处理这类流量
 * 
 * 握手消息使用高优先级的原因：
 * 1. 连接建立：握手失败会导致整个VPN连接不可用
 * 2. 延迟敏感：握手超时会触发重试，影响用户体验  
 * 3. 流量较少：握手消息相对较少，不会占用过多带宽
 * 4. 网络优化：帮助VPN在拥塞网络中快速建立连接
 */
enum { HANDSHAKE_DSCP = 0x88 /* AF41, plus 00 ECN */ };

