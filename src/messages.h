/**
 * message_data_len - 计算完整数据消息的长度
 * @plain_len: 明文IP数据包的长度
 * 
 * 长度计算组成：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                    数据消息总长度                            │
 * ├─────────────────┬─────────────────┬─────────────────────────┤
 * │  消息头部固定    │    明文数据     │      AEAD 开销         │
 * │     16字节      │   plain_len     │      16字节            │
 * │                │                 │                       │
 * │ • header(4)     │ • IP数据包内容   │ • Poly1305 MAC标签     │
 * │ • key_idx(4)    │ • 变长         │ • 完整性验证           │
 * │ • counter(8)    │               │                       │
 * └─────────────────┴─────────────────┴─────────────────────────┘
 * 
 * 返回值：完整WireGuard数据消息的总字节数
 */
#define message_data_len(plain_len) \
	(noise_encrypted_len(plain_len) + sizeof(struct message_data))

