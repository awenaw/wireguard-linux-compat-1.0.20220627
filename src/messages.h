/**
 * limits - WireGuard 协议的各种安全阈值和性能限制
 * 
 * 这些限制确保协议的安全性、性能和可靠性：
 * 
 * 密钥生命周期管理：
 * ┌─────────────────┐    ┌─────────────────┐    ┌─────────────────┐
 * │   新密钥建立     │───►│   密钥使用期    │───►│   强制更新密钥   │
 * │   Key Created   │    │  Key In Use     │    │  Forced Rekey   │
 * └─────────────────┘    └─────────────────┘    └─────────────────┘
 *         │                      │                      │
 *    0 消息数量           REKEY_AFTER_MESSAGES    REJECT_AFTER_MESSAGES
 *    0 时间              REKEY_AFTER_TIME        REJECT_AFTER_TIME
 * 
 * 握手频率限制：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                    握手频率控制                              │
 * │  ┌─────────┐  ┌─────────┐  ┌─────────┐  ┌─────────┐       │
 * │  │ 握手#1  │  │ 握手#2  │  │   ...   │  │ 握手#50 │  ←限制│
 * │  └─────────┘  └─────────┘  └─────────┘  └─────────┘       │
 * │  ←────────────── 1 秒时间窗口 ─────────────→              │
 * └─────────────────────────────────────────────────────────────┘
 */
enum limits {
	/* ═══ 密钥重新协商限制 ═══ */
	
	/* 触发重新密钥协商的消息数量阈值 (2^60 ≈ 10^18 消息)
	 * 
	 * 为什么选择 2^60：
	 * • ChaCha20 的安全分析表明在 2^64 消息前是安全的
	 * • 2^60 提供了 16 倍的安全边界 (2^64 / 2^60 = 16)
	 * • 实际上很难达到这个数量（需要持续高速传输数年）
	 * • 提前重新协商密钥确保前向保密性
	 * 
	 * 安全原理：
	 * - 防止密码学攻击：限制单个密钥的使用量
	 * - 提供前向保密：定期更新会话密钥
	 * - 符合AEAD最佳实践：避免nonce重复使用的风险 */
	REKEY_AFTER_MESSAGES = 1ULL << 60,
	
	/* 强制拒绝消息的数量阈值 (接近 2^64 的最大值)
	 * 
	 * 计算原理：U64_MAX - COUNTER_WINDOW_SIZE - 1
	 * • 为滑动窗口预留空间，避免整数溢出
	 * • 确保计数器不会回绕到 0
	 * • 这是密码学安全的硬限制，绝不能突破
	 * 
	 * 达到此限制时：
	 * - 立即停止使用当前密钥对
	 * - 强制发起新的握手协商
	 * - 丢弃所有使用旧密钥的消息 */
	REJECT_AFTER_MESSAGES = U64_MAX - COUNTER_WINDOW_SIZE - 1,
	
	/* ═══ 握手时序控制 ═══ */
	
	/* 握手重试间隔 (5秒)
	 * 平衡响应性和网络负载：
	 * • 足够长：避免网络拥塞时的无效重试
	 * • 足够短：确保连接建立的用户体验
	 * • 指数退避：配合 MAX_TIMER_HANDSHAKES 实现 */
	REKEY_TIMEOUT = 5,
	
	/* 握手超时随机抖动最大值 (约333毫秒)
	 * 
	 * 为什么需要随机抖动：
	 * • 避免"惊群效应"：防止多个对等体同时重试
	 * • 网络负载均衡：将重试时间分散
	 * • 时序攻击防护：增加握手时序的随机性
	 * 
	 * 实现：在基础超时时间上增加 0-333ms 的随机延迟 */
	REKEY_TIMEOUT_JITTER_MAX_JIFFIES = HZ / 3,
	
	/* 基于时间的密钥重新协商触发 (120秒)
	 * 
	 * 时间vs消息数量的双重保护：
	 * • 即使消息很少，也要定期更新密钥
	 * • 确保长期连接的安全性
	 * • 2分钟是安全性和便利性的平衡点 */
	REKEY_AFTER_TIME = 120,
	
	/* 基于时间的强制拒绝阈值 (180秒)
	 * 
	 * 硬性安全边界：
	 * • 绝对不允许超过3分钟不更新密钥
	 * • 防止时钟攻击和长期密钥暴露
	 * • 为 REKEY_AFTER_TIME 提供 60 秒的缓冲时间 */
	REJECT_AFTER_TIME = 180,
	
	/* ═══ DoS 防护限制 ═══ */
	
	/* 每秒最大握手发起数量 (50次/秒)
	 * 
	 * DoS 攻击防护：
	 * • 限制握手频率，防止计算资源耗尽
	 * • 50次/秒足够应对合理的网络条件
	 * • 超过此限制将触发 Cookie 机制
	 * 
	 * 实现机制：
	 * - 使用令牌桶算法
	 * - 平滑处理突发流量
	 * - 与 Cookie 机制协同工作 */
	INITIATIONS_PER_SECOND = 50,
	
	/* 每个设备最大对等体数量 (2^20 = 1,048,576)
	 * 
	 * 资源管理：
	 * • 防止内存耗尽：每个 peer 占用一定内存
	 * • 哈希表性能：与 peerlookup.c 中的分析一致
	 * • 实际合理上限：大多数用例远少于此数量
	 * 
	 * 设计考虑：
	 * - 大型企业网络：支持百万级用户
	 * - 哈希表效率：保持查找性能
	 * - 内存使用可预测：便于系统规划 */
	MAX_PEERS_PER_DEVICE = 1U << 20,
	
	/* ═══ 连接保持机制 ═══ */
	
	/* Keepalive 超时时间 (10秒)
	 * 
	 * NAT 穿越和连接保持：
	 * • 大多数家用路由器的NAT超时为30-60秒
	 * • 10秒间隔确保NAT映射不会过期
	 * • 平衡网络开销和连接可靠性 */
	KEEPALIVE_TIMEOUT = 10,
	
	/* 最大握手重试次数 (18次)
	 * 计算：90秒 ÷ 5秒间隔 = 18次
	 * 
	 * 重试策略：
	 * • 总重试时间：90秒（1.5分钟）
	 * • 避免无限重试：防止资源泄露
	 * • 用户体验平衡：足够的时间建立连接 */
	MAX_TIMER_HANDSHAKES = 90 / REKEY_TIMEOUT,
	
	/* ═══ 队列深度限制 ═══ */
	
	/* 最大排队的入站握手数量 (4096)
	 * TODO: 未来用 Dynamic Queue Limits (DQL) 替换
	 * 
	 * 内存保护：
	 * • 防止握手洪水攻击耗尽内存
	 * • 4096 足够处理高负载峰值
	 * • 配合 Cookie 机制提供多层防护 */
	MAX_QUEUED_INCOMING_HANDSHAKES = 4096,
	
	/* 每个对等体最大暂存数据包数量 (128)
	 * 
	 * 握手期间的数据包缓存：
	 * • 在握手完成前缓存数据包
	 * • 避免数据丢失和重传
	 * • 128 个包足够应对握手延迟 */
	MAX_STAGED_PACKETS = 128,
	
	/* 最大排队数据包数量 (1024)
	 * TODO: 未来用 Dynamic Queue Limits (DQL) 替换
	 * 
	 * 加密队列深度：
	 * • 平衡延迟和吞吐量
	 * • 防止队列爆炸影响系统性能
	 * • 适应高速网络环境 */
	MAX_QUEUED_PACKETS = 1024
};

