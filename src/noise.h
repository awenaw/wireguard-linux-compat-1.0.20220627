/**
 * wg_noise_handshake_init - 初始化握手状态结构
 * @handshake: 要初始化的握手结构指针
 * @static_identity: 本地静态身份指针
 * @peer_public_key: 对方静态公钥 (32字节)
 * @peer_preshared_key: 预共享密钥 (32字节, 可为NULL)
 * @peer: 关联的对等体结构指针
 * 
 * 功能描述：
 * 为一个新的对等体连接初始化握手状态结构，设置必要的密钥材料
 * 和身份信息，准备进行Noise协议握手。
 * 
 * 初始化流程：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                  握手初始化流程                              │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  1. 清零握手结构                                            │
 * │     └── memset(handshake, 0, sizeof(*handshake))          │
 * │                                                             │
 * │  2. 设置静态身份                                            │
 * │     └── handshake->static_identity = static_identity       │
 * │                                                             │
 * │  3. 复制对方公钥                                            │
 * │     └── memcpy(handshake->remote_static, peer_public_key)  │
 * │                                                             │
 * │  4. 预计算静态DH                                            │
 * │     └── curve25519(handshake->precomputed_static_static)   │
 * │                                                             │
 * │  5. 设置预共享密钥 (如果提供)                               │
 * │     └── memcpy(handshake->preshared_key, peer_preshared_key)│
 * │                                                             │
 * │  6. 初始化锁和索引                                          │
 * │     └── init_rwsem(&handshake->lock)                       │
 * │                                                             │
 * │  7. 设置初始状态                                            │
 * │     └── handshake->state = HANDSHAKE_ZEROED               │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 参数验证：
 * - static_identity 必须已正确初始化
 * - peer_public_key 必须是有效的Curve25519公钥
 * - peer_preshared_key 可以为NULL (表示不使用PSK)
 * - peer 必须是有效的对等体结构
 * 
 * 性能优化：
 * - 预计算静态DH避免握手时重复计算
 * - 使用内存池减少动态分配开销
 * - 锁结构预初始化避免运行时开销
 */
void wg_noise_handshake_init(struct noise_handshake *handshake,
			     struct noise_static_identity *static_identity,
			     const u8 peer_public_key[NOISE_PUBLIC_KEY_LEN],
			     const u8 peer_preshared_key[NOISE_SYMMETRIC_KEY_LEN],
			     struct wg_peer *peer);

/**
 * wg_noise_handshake_clear - 清理握手状态和密钥材料
 * @handshake: 要清理的握手结构指针
 * 
 * 功能描述：
 * 安全地清除握手过程中的所有敏感数据，包括临时密钥、哈希状态和
 * 协商参数，防止内存泄露敏感信息。
 * 
 * 清理内容：
 * 1. 临时私钥 (ephemeral_private) - 安全清零
 * 2. 对方临时公钥 (remote_ephemeral) - 清零
 * 3. 哈希链状态 (hash, chaining_key) - 清零
 * 4. 握手状态重置为 HANDSHAKE_ZEROED
 * 5. 时间戳和计数器清零
 * 6. 哈希表条目移除
 * 
 * 安全措施：
 * - 使用 memzero_explicit() 防止编译器优化
 * - 多次覆写敏感内存区域
 * - 清理后立即刷新CPU缓存
 * 
 * 调用时机：
 * - 握手完成后
 * - 握手失败时
 * - 对等体断开连接时
 * - 超时清理时
 */
void wg_noise_handshake_clear(struct noise_handshake *handshake);

/**
 * wg_noise_reset_last_sent_handshake - 重置最后握手发送时间
 * @handshake_ns: 握手时间戳的原子变量指针
 * 
 * 功能描述：
 * 将最后握手发送时间设置为一个较早的时间，使得握手定时器认为
 * 已经超过了重新握手的间隔，可以立即发起新的握手。
 * 
 * 实现原理：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                 握手时间重置逻辑                             │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  当前时间                                                   │
 * │      │                                                     │
 * │      ▼                                                     │
 * │  ────●────────────────────────────────────────────────────→│
 * │      │                                                     │
 * │      │◄────── (REKEY_TIMEOUT + 1) 秒 ──────►              │
 * │      │                                      │              │
 * │      ▼                                      │              │
 * │  设置的"过去"时间点                           │              │
 * │                                             │              │
 * │  结果：定时器检查时发现已超过 REKEY_TIMEOUT    │              │
 * │       立即触发新握手                          │              │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 使用场景：
 * - 强制立即重新握手
 * - 密钥过期强制更新
 * - 网络状态变化后快速恢复
 * - 调试和测试目的
 * 
 * 线程安全：
 * - 使用原子操作，支持并发调用
 * - 不需要额外的锁保护
 * - 时间设置操作是幂等的
 */
static inline void wg_noise_reset_last_sent_handshake(atomic64_t *handshake_ns)
{
	/* 
	 * 计算一个"足够早"的时间点：
	 * 1. 获取当前系统运行时间 (ktime_get_coarse_boottime_ns)
	 * 2. 减去 (REKEY_TIMEOUT + 1) 秒的纳秒数
	 * 3. 原子设置到握手时间戳变量
	 * 
	 * 效果：使定时器认为上次握手时间已经超过重新握手间隔
	 */
	atomic64_set(handshake_ns, ktime_get_coarse_boottime_ns() -
				       (u64)(REKEY_TIMEOUT + 1) * NSEC_PER_SEC);
}

