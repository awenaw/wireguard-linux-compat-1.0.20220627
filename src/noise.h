/**
 * struct noise_static_identity - 长期静态身份密钥对
 * 
 * 功能描述：
 * 管理设备的长期身份信息，包括静态Curve25519密钥对。这些密钥在设备
 * 整个生命周期内保持相对稳定，用于身份认证和初始密钥协商。
 * 
 * 密钥安全模型：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                   静态密钥安全架构                           │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  ┌─────────────────┐          ┌─────────────────┐           │
 * │  │   私钥存储区    │          │   公钥分发区    │           │
 * │  │ Private Key     │          │  Public Key     │           │
 * │  │   Storage       │          │ Distribution    │           │
 * │  │                │          │                 │           │
 * │  │ • 内存保护      │          │ • 公开可见      │           │
 * │  │ • 访问控制      │    vs    │ • 可自由复制    │           │
 * │  │ • 及时清零      │          │ • 身份标识      │           │
 * │  │ • 权限检查      │          │ • 完整性校验    │           │
 * │  └─────────────────┘          └─────────────────┘           │
 * │           │                            │                   │
 * │           └─────────┬──────────────────┘                   │
 * │                     │                                      │
 * │  ┌─────────────────────────────────────────────────────┐   │
 * │  │                密钥对数学关系                        │   │
 * │  │                                                     │   │
 * │  │  private_key × G = public_key                       │   │
 * │  │  (G 是 Curve25519 基点)                            │   │
 * │  │                                                     │   │
 * │  │  性质：                                             │   │
 * │  │  • 单向函数：由私钥计算公钥容易                     │   │
 * │  │  • 抗逆向：由公钥推导私钥困难                       │   │
 * │  │  • 离散对数：基于椭圆曲线离散对数难题               │   │
 * │  └─────────────────────────────────────────────────────┘   │
 * └─────────────────────────────────────────────────────────────┘
 */
struct noise_static_identity {
	u8 static_public[NOISE_PUBLIC_KEY_LEN];
	                                   /* 静态公钥 (Curve25519)
	                                    * 长度：32字节 (256位)
	                                    * 用途：身份标识和密钥协商
	                                    * 分发：可公开，包含在配置文件中
	                                    * 验证：通过签名或预共享方式验证
	                                    * 格式：压缩点表示法
	                                    */

	u8 static_private[NOISE_PUBLIC_KEY_LEN];
	                                   /* 静态私钥 (Curve25519)
	                                    * 长度：32字节 (256位)  
	                                    * 安全：严格保密，仅本设备知晓
	                                    * 用途：ECDH密钥协商和身份证明
	                                    * 生成：高质量随机数生成器
	                                    * 存储：内存保护，使用后清零
	                                    * 权限：需要管理员权限访问
	                                    */

	struct rw_semaphore lock;         /* 读写信号量保护锁
	                                   * 用途：保护密钥对的读写访问
	                                   * 类型：读写锁，支持并发读取
	                                   * 写锁：密钥更新、初始化时获取
	                                   * 读锁：握手和加密操作时获取
	                                   * 优势：读操作可并行执行
	                                   */

	bool has_identity;                /* 身份有效性标志
	                                   * true：密钥对已正确初始化
	                                   * false：尚未配置或已清除
	                                   * 检查：操作前必须验证此标志
	                                   * 设置：密钥配置成功后置true
	                                   */
};

