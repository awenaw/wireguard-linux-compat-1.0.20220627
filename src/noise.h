/**
 * struct noise_symmetric_key - 对称加密密钥信息
 * 
 * 功能描述：
 * 存储用于数据包加密/解密的对称密钥及其元数据。每个密钥都有明确的
 * 生命周期管理，支持密钥轮换和过期检测。
 * 
 * 密钥生命周期：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                    密钥生命周期图                            │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  创建    激活         使用中         即将过期    过期        │
 * │   │       │            │              │         │         │
 * │   ▼       ▼            ▼              ▼         ▼         │
 * │ ─────────────────────────────────────────────────────────→ │
 * │   │       │            │              │         │         │
 * │   │    is_valid     正常加密/解密    轮换提醒   停止使用    │
 * │   │     = true        操作          新密钥     = false     │
 * │   │                                                        │
 * │ birthdate ──────── 120秒 ────────── 180秒 ──────────────→ │
 * │                  (重新握手)       (强制过期)               │
 * └─────────────────────────────────────────────────────────────┘
 */
struct noise_symmetric_key {
	u8 key[NOISE_SYMMETRIC_KEY_LEN];    /* ChaCha20Poly1305 对称密钥
	                                     * 长度：32字节 (256位)
	                                     * 用途：数据包加密/解密
	                                     * 来源：HKDF 密钥派生函数
	                                     */
	u64 birthdate;                      /* 密钥创建时间戳 (纳秒)
	                                     * 用途：计算密钥年龄和过期时间
	                                     * 基准：系统启动时间 (boottime)
	                                     * 精度：纳秒级，防止时钟调整影响
	                                     */
	bool is_valid;                      /* 密钥有效性标志
	                                     * true：可用于加密/解密操作
	                                     * false：已过期，应停止使用
	                                     * 原子性：由外部锁机制保证
	                                     */
};

