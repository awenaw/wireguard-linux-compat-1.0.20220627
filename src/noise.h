/*
 * ===================================================================
 * WireGuard Noise 协议实现头文件
 * ===================================================================
 * 
 * 本文件实现了 WireGuard 基于 Noise 协议框架的加密握手和密钥管理系统。
 * Noise 协议是一个现代密码学框架，为端到端加密通信提供了安全的握手模式。
 * 
 * WireGuard 使用的具体 Noise 协议变种：
 * - 模式：Noise_IKpsk2_25519_ChaChaPoly_BLAKE2s
 * - I：发起者有静态密钥对
 * - K：响应者静态公钥已知
 * - psk2：预共享密钥在第二轮消息中混入
 * - 25519：Curve25519 椭圆曲线 DH
 * - ChaChaPoly：ChaCha20Poly1305 AEAD 算法
 * - BLAKE2s：BLAKE2s 哈希函数
 * 
 * 整体架构图：
 * ┌─────────────────────────────────────────────────────────────────┐
 * │                  WireGuard Noise 协议架构                        │
 * ├─────────────────────────────────────────────────────────────────┤
 * │                                                                 │
 * │ ┌─────────────────┐      ┌─────────────────┐                   │
 * │ │   静态身份       │      │   握手状态机     │                   │
 * │ │ Static Identity │      │ Handshake FSM   │                   │
 * │ │                │      │                 │                   │
 * │ │ • 长期密钥对     │      │ • 临时密钥对     │                   │
 * │ │ • 预共享密钥     │      │ • 协议状态       │                   │
 * │ └─────────────────┘      └─────────────────┘                   │
 * │          │                        │                           │
 * │          │                        │                           │
 * │          └────────┬───────────────┘                           │
 * │                   │                                           │
 * │ ┌─────────────────────────────────────────────────────────┐   │
 * │ │                 密钥对管理器                              │   │
 * │ │              Keypair Manager                            │   │
 * │ │                                                         │   │
 * │ │  ┌─────────────┐ ┌─────────────┐ ┌─────────────┐        │   │
 * │ │  │ Previous    │ │ Current     │ │ Next        │        │   │
 * │ │  │ Keypair     │ │ Keypair     │ │ Keypair     │        │   │
 * │ │  └─────────────┘ └─────────────┘ └─────────────┘        │   │
 * │ │         │               │               │               │   │
 * │ └─────────────────────────────────────────────────────────┘   │
 * │           │               │               │                   │
 * │           └───────────────┼───────────────┘                   │
 * │                           │                                   │
 * │ ┌─────────────────────────────────────────────────────────┐   │
 * │ │              数据包加密/解密引擎                          │   │
 * │ │                                                         │   │
 * │ │ • ChaCha20Poly1305 AEAD 加密                            │   │
 * │ │ • 重放攻击保护 (Anti-replay)                            │   │
 * │ │ • 发送计数器管理                                        │   │
 * │ └─────────────────────────────────────────────────────────┘   │
 * └─────────────────────────────────────────────────────────────────┘
 * 
 * 协议流程概览：
 * 
 * 发起者 (Initiator)           响应者 (Responder)
 *     │                            │
 *     │ ── 握手初始化消息 ──→      │  (包含发起者临时公钥)
 *     │    [ephemeral_public]      │
 *     │                            │
 *     │ ←── 握手响应消息 ──        │  (包含响应者临时公钥)
 *     │    [ephemeral_public]      │
 *     │                            │
 *     │ ── 首个加密数据包 ──→      │  (建立会话)
 *     │                            │
 *     │ ←──→ 加密数据传输 ←──→     │  (使用派生密钥)
 *     │                            │
 * 
 * 安全特性：
 * 1. 前向安全性 (Forward Secrecy)：临时密钥确保历史通信安全
 * 2. 身份隐藏 (Identity Hiding)：静态公钥被加密传输
 * 3. 抗重放攻击 (Anti-replay)：序列号和滑动窗口保护
 * 4. 完美前向安全 (Perfect Forward Secrecy)：定期密钥轮换
 * 5. 抗降级攻击 (Downgrade Resistance)：固定的强密码套件
 */

