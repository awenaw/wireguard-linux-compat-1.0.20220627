/**
 * struct noise_keypair - 完整的双向密钥对
 * 
 * 功能描述：
 * 表示一个完整的加密会话，包含发送和接收两个方向的密钥、计数器和
 * 元数据。每个密钥对对应一次成功的握手过程。
 * 
 * 密钥对架构：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                     密钥对内部结构                           │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  ┌─────────────────┐          ┌─────────────────┐           │
 * │  │   发送密钥      │          │   接收密钥      │           │
 * │  │  Sending Key    │          │  Receiving Key  │           │
 * │  │                │          │                 │           │
 * │  │ • 加密密钥      │          │ • 解密密钥      │           │
 * │  │ • 发送计数器    │          │ • 重放计数器    │           │
 * │  │ • 原子操作      │          │ • 滑动窗口      │           │
 * │  └─────────────────┘          └─────────────────┘           │
 * │           │                            │                   │
 * │           └─────────┬──────────────────┘                   │
 * │                     │                                      │
 * │  ┌─────────────────────────────────────────────────────┐   │
 * │  │                密钥对元数据                          │   │
 * │  │                                                     │   │
 * │  │ • 远程索引 (remote_index)                          │   │
 * │  │ • 握手角色 (i_am_the_initiator)                    │   │
 * │  │ • 引用计数 (refcount)                              │   │
 * │  │ • RCU 延迟释放 (rcu)                               │   │
 * │  │ • 哈希表条目 (entry)                               │   │
 * │  └─────────────────────────────────────────────────────┘   │
 * └─────────────────────────────────────────────────────────────┘
 */
struct noise_keypair {
	struct index_hashtable_entry entry; /* 哈希表索引条目
	                                     * 用途：快速查找密钥对
	                                     * 索引：本地生成的32位索引
	                                     * 冲突：链式哈希解决
	                                     */

	/* === 发送方向密钥和状态 === */
	struct noise_symmetric_key sending; /* 发送加密密钥
	                                     * 用途：加密出站数据包
	                                     * 算法：ChaCha20Poly1305
	                                     * 派生：握手完成后生成
	                                     */
	atomic64_t sending_counter;         /* 发送包序列号计数器
	                                     * 特性：原子64位整数，线程安全
	                                     * 用途：防重放，每包递增
	                                     * 范围：0 到 2^64-1
	                                     * 重置：密钥轮换时归零
	                                     */

	/* === 接收方向密钥和状态 === */
	struct noise_symmetric_key receiving; /* 接收解密密钥
	                                       * 用途：解密入站数据包
	                                       * 对应：发送方的发送密钥
	                                       * 验证：AEAD 认证标签
	                                       */
	struct noise_replay_counter receiving_counter;
	                                       /* 接收重放保护计数器
	                                        * 功能：防止重放攻击
	                                        * 机制：滑动窗口 + 位图
	                                        * 窗口：可配置大小
	                                        */

	/* === 握手和会话元数据 === */
	__le32 remote_index;                /* 远程端索引 (小端序)
	                                     * 用途：标识远程端的密钥对
	                                     * 格式：32位小端序整数
	                                     * 来源：握手消息交换
	                                     */
	bool i_am_the_initiator;           /* 握手发起者标志
	                                    * true：本端发起握手
	                                    * false：本端响应握手
	                                    * 影响：密钥派生和角色逻辑
	                                    */

	/* === 内存管理和生命周期 === */
	struct kref refcount;              /* 内核引用计数器
	                                    * 用途：安全的内存管理
	                                    * 机制：get/put 操作
	                                    * 释放：计数归零时自动清理
	                                    */
	struct rcu_head rcu;              /* RCU 延迟释放头
	                                   * 用途：无锁并发读取
	                                   * 机制：读-复制-更新
	                                   * 优势：高性能并发访问
	                                   */
	u64 internal_id;                  /* 内部唯一标识符
	                                   * 用途：调试和日志记录
	                                   * 特性：单调递增
	                                   * 范围：64位整数空间
	                                   */
};

