/**
 * wg_noise_precompute_static_static - 预计算静态DH共享密钥
 * @peer: 目标对等体指针
 * 
 * 功能描述：
 * 预先计算本地静态私钥与对方静态公钥的椭圆曲线Diffie-Hellman
 * 共享密钥，并缓存结果以优化握手性能。
 * 
 * DH计算原理：
 * ┌─────────────────────────────────────────────────────────────┐
 * │              椭圆曲线DH密钥协商                              │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  本地端：                    对方端：                       │
 * │  ┌─────────────────┐        ┌─────────────────┐             │
 * │  │ 私钥: a         │        │ 公钥: B = b×G   │             │
 * │  │ 公钥: A = a×G   │        │ 私钥: b         │             │
 * │  └─────────────────┘        └─────────────────┘             │
 * │           │                            │                   │
 * │           └─────────┬──────────────────┘                   │
 * │                     │                                      │
 * │  计算共享密钥：                                             │
 * │  shared_secret = a × B = a × (b × G) = (a × b) × G        │
 * │                = b × A = b × (a × G) = (b × a) × G        │
 * │                                                             │
 * │  结果：双方计算出相同的共享密钥                              │
 * │       shared_secret 用于后续密钥派生                        │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 性能优化：
 * - 预计算避免握手时的昂贵计算
 * - 结果可缓存直到密钥更新
 * - 减少握手延迟和CPU开销
 * 
 * 调用时机：
 * - 对等体初次配置时
 * - 静态密钥更新后
 * - 配置变更时
 */
void wg_noise_precompute_static_static(struct wg_peer *peer);

