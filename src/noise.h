/**
 * wg_noise_handshake_create_initiation - 创建握手初始化消息
 * @dst: 输出消息缓冲区指针
 * @handshake: 握手状态结构指针
 * 
 * 返回值：成功创建返回true，失败返回false
 * 
 * 功能描述：
 * 构造Noise协议的第一个消息（握手初始化），包含发起者的身份证明
 * 和临时公钥。这个消息启动整个握手过程。
 * 
 * 消息结构：
 * ┌─────────────────────────────────────────────────────────────┐
 * │              握手初始化消息格式                              │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  ┌─────────────┐ ┌─────────────┐ ┌─────────────┐           │
 * │  │   消息头    │ │  临时公钥   │ │  加密负载   │           │
 * │  │   Header    │ │ Ephemeral   │ │ Encrypted   │           │
 * │  │             │ │ Public Key  │ │  Payload    │           │
 * │  │ • 消息类型  │ │             │ │             │           │
 * │  │ • 发送索引  │ │ • 32字节    │ │ • 身份证明  │           │
 * │  │ • 保留字段  │ │ • Curve25519│ │ • 时间戳    │           │
 * │  └─────────────┘ └─────────────┘ └─────────────┘           │
 * │        4字节         32字节         变长+16字节MAC          │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 加密过程：
 * 1. 生成临时密钥对 (ephemeral keypair)
 * 2. 执行DH计算: ephemeral_private × remote_static
 * 3. 混入预共享密钥 (如果配置)
 * 4. 加密发起者静态公钥和时间戳
 * 5. 计算消息认证码 (MAC)
 * 6. 更新握手状态为 HANDSHAKE_CREATED_INITIATION
 * 
 * 安全特性：
 * - 身份隐藏：静态公钥被加密传输
 * - 前向安全：使用临时密钥
 * - 重放保护：包含单调递增时间戳
 * - 完整性保护：AEAD提供认证
 */
bool
wg_noise_handshake_create_initiation(struct message_handshake_initiation *dst,
				     struct noise_handshake *handshake);

/**
 * wg_noise_handshake_consume_initiation - 处理握手初始化消息
 * @src: 接收到的消息指针
 * @wg: WireGuard设备结构指针
 * 
 * 返回值：成功时返回对等体指针，失败返回NULL
 * 
 * 功能描述：
 * 验证并处理接收到的握手初始化消息，提取对方身份信息，
 * 为发送握手响应做准备。
 * 
 * 处理流程：
 * ┌─────────────────────────────────────────────────────────────┐
 * │              握手初始化消息处理流程                          │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  1. 消息格式验证                                            │
 * │     ├── 检查消息类型和长度                                  │
 * │     └── 验证索引字段有效性                                  │
 * │                                                             │
 * │  2. 查找或创建握手状态                                      │
 * │     ├── 根据发送索引查找现有握手                            │
 * │     └── 如需要则创建新握手状态                              │
 * │                                                             │
 * │  3. 密钥协商验证                                            │
 * │     ├── 提取对方临时公钥                                    │
 * │     ├── 执行DH计算验证                                      │
 * │     └── 检查预共享密钥匹配                                  │
 * │                                                             │
 * │  4. 解密和验证负载                                          │
 * │     ├── 解密对方静态公钥                                    │
 * │     ├── 验证时间戳防重放                                    │
 * │     └── 检查MAC完整性                                       │
 * │                                                             │
 * │  5. 更新握手状态                                            │
 * │     ├── 保存对方临时公钥                                    │
 * │     ├── 更新哈希链状态                                      │
 * │     └── 状态转换至CONSUMED_INITIATION                       │
 * │                                                             │
 * │  6. 返回匹配的对等体                                        │
 * │     └── 根据解密的静态公钥查找对等体                        │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 安全检查：
 * - 时间戳必须比上次更新 (防重放)
 * - MAC验证必须通过 (防篡改)
 * - 静态公钥必须匹配已知对等体
 * - DH计算结果必须有效
 * 
 * 错误处理：
 * - 验证失败时安全清理敏感数据
 * - 记录安全事件便于审计
 * - 限制失败尝试防止DOS攻击
 */
struct wg_peer *
wg_noise_handshake_consume_initiation(struct message_handshake_initiation *src,
				      struct wg_device *wg);

/**
 * wg_noise_handshake_create_response - 创建握手响应消息
 * @dst: 输出消息缓冲区指针
 * @handshake: 握手状态结构指针
 * 
 * 返回值：成功创建返回true，失败返回false
 * 
 * 功能描述：
 * 创建Noise协议的第二个消息（握手响应），包含响应者的临时公钥
 * 和加密确认信息。完成双向认证过程。
 * 
 * 消息结构：
 * ┌─────────────────────────────────────────────────────────────┐
 * │              握手响应消息格式                                │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  ┌─────────────┐ ┌─────────────┐ ┌─────────────┐           │
 * │  │   消息头    │ │  临时公钥   │ │  加密确认   │           │
 * │  │   Header    │ │ Ephemeral   │ │ Encrypted   │           │
 * │  │             │ │ Public Key  │ │   Empty     │           │
 * │  │ • 消息类型  │ │             │ │             │           │
 * │  │ • 接收索引  │ │ • 32字节    │ │ • psk混入   │           │
 * │  │ • 发送索引  │ │ • Curve25519│ │ • MAC验证   │           │
 * │  └─────────────┘ └─────────────┘ └─────────────┘           │
 * │        8字节         32字节         16字节MAC              │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 密钥派生过程：
 * 1. 生成响应者临时密钥对
 * 2. 执行三次DH计算：
 *    - ephemeral_local × ephemeral_remote
 *    - ephemeral_local × static_remote  
 *    - static_local × ephemeral_remote
 * 3. 混入预共享密钥 (第二轮)
 * 4. 派生发送和接收密钥
 * 5. 更新状态为 HANDSHAKE_CREATED_RESPONSE
 * 
 * 关键区别：
 * - 响应消息较短，主要提供临时公钥
 * - 预共享密钥在此阶段混入哈希链
 * - 三次DH提供完美前向安全性
 * - 响应后立即可派生会话密钥
 */
bool wg_noise_handshake_create_response(struct message_handshake_response *dst,
					struct noise_handshake *handshake);

/**
 * wg_noise_handshake_consume_response - 处理握手响应消息
 * @src: 接收到的响应消息指针
 * @wg: WireGuard设备结构指针
 * 
 * 返回值：成功时返回对等体指针，失败返回NULL
 * 
 * 功能描述：
 * 验证并处理握手响应消息，完成密钥协商过程，派生最终的会话密钥。
 * 这是握手协议的最后一步。
 * 
 * 处理和验证：
 * 1. 查找对应的握手状态 (通过接收索引)
 * 2. 提取响应者临时公钥
 * 3. 执行相同的三次DH计算
 * 4. 验证预共享密钥一致性
 * 5. 检查MAC完整性
 * 6. 派生最终会话密钥对
 * 7. 状态转换为 HANDSHAKE_CONSUMED_RESPONSE
 * 
 * 会话密钥派生：
 * ```
 * 发送密钥 = HKDF-Expand(chaining_key, "sending key", 32)
 * 接收密钥 = HKDF-Expand(chaining_key, "receiving key", 32)  
 * ```
 * 
 * 成功标志：
 * - 握手完成，可开始加密数据传输
 * - 密钥对已就绪，等待数据包激活
 * - 握手状态可清理释放
 */
struct wg_peer *
wg_noise_handshake_consume_response(struct message_handshake_response *src,
				    struct wg_device *wg);

/**
 * wg_noise_handshake_begin_session - 开始新会话
 * @handshake: 已完成的握手状态指针
 * @keypairs: 密钥对集合指针
 * 
 * 返回值：成功开始会话返回true，失败返回false
 * 
 * 功能描述：
 * 将成功完成的握手转换为活跃的加密会话，创建密钥对并安装到
 * 密钥对管理器中。这是从握手阶段到数据传输阶段的过渡点。
 * 
 * 会话建立流程：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                    会话建立流程                              │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  1. 验证握手完成状态                                        │
 * │     ├── 检查状态为CONSUMED_RESPONSE                         │
 * │     └── 验证密钥材料完整性                                  │
 * │                                                             │
 * │  2. 创建新密钥对                                            │
 * │     ├── 分配密钥对结构                                      │
 * │     ├── 复制派生的会话密钥                                  │
 * │     ├── 初始化计数器和重放保护                              │
 * │     └── 设置握手角色标志                                    │
 * │                                                             │
 * │  3. 安装到密钥对集合                                        │
 * │     ├── 获取更新锁                                          │
 * │     ├── 设置为next_keypair                                  │
 * │     └── 释放更新锁                                          │
 * │                                                             │
 * │  4. 清理握手状态                                            │
 * │     ├── 清零敏感的握手数据                                  │
 * │     ├── 重置握手状态为ZEROED                                │
 * │     └── 移除握手索引                                        │
 * │                                                             │
 * │  5. 激活会话功能                                            │
 * │     ├── 启动重放保护                                        │
 * │     ├── 重置发送计数器                                      │
 * │     └── 准备数据包处理                                      │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 密钥对激活：
 * - 新密钥对作为next_keypair安装
 * - 等待接收到使用此密钥的数据包时自动激活
 * - 激活后成为current_keypair用于正常通信
 * 
 * 安全清理：
 * - 握手过程中的临时密钥被安全清零
 * - 握手状态重置防止重用
 * - 哈希表条目清理避免索引冲突
 * 
 * 这个函数标志着从密钥协商阶段到安全数据传输阶段的成功过渡。
 */
