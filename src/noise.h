/**
 * struct noise_handshake - 握手过程状态和临时数据
 * 
 * 功能描述：
 * 管理一次完整握手过程中的所有临时状态、密钥材料和协议数据。
 * 每个对等体连接维护一个握手实例，支持并发握手和状态恢复。
 * 
 * 握手数据流图：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                  握手过程数据流                              │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  输入数据：                                                 │
 * │  ┌─────────────────┐  ┌─────────────────┐                  │
 * │  │ 静态身份密钥对   │  │ 对方公钥        │                  │
 * │  │ Static Keypair  │  │ Peer Public Key │                  │
 * │  └─────────────────┘  └─────────────────┘                  │
 * │           │                     │                          │
 * │           └──────┬──────────────┘                          │
 * │                  │                                         │
 * │                  ▼                                         │
 * │  ┌─────────────────────────────────────────────────────┐   │
 * │  │              握手密钥派生                            │   │
 * │  │                                                     │   │
 * │  │  1. 生成临时密钥对 (ephemeral_private)               │   │
 * │  │  2. 计算静态DH (precomputed_static_static)          │   │
 * │  │  3. 混入预共享密钥 (preshared_key)                  │   │
 * │  │  4. 更新链式密钥 (chaining_key)                     │   │
 * │  │  5. 计算消息哈希 (hash)                             │   │
 * │  └─────────────────────────────────────────────────────┘   │
 * │                  │                                         │
 * │                  ▼                                         │
 * │  输出数据：                                                 │
 * │  ┌─────────────────┐  ┌─────────────────┐                  │
 * │  │ 会话密钥对      │  │ 握手认证数据    │                  │
 * │  │ Session Keys    │  │ Auth Data       │                  │
 * │  └─────────────────┘  └─────────────────┘                  │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 并发安全设计：
 * - 读写锁保护握手状态修改
 * - 部分字段初始化后不可变
 * - 时间戳防止并发握手冲突
 * - 原子状态转换保证一致性
 */
struct noise_handshake {
	struct index_hashtable_entry entry; /* 哈希表索引条目
	                                     * 用途：根据握手索引快速查找
	                                     * 索引：消息中携带的32位标识
	                                     * 冲突：链表法解决哈希冲突
	                                     * 生命：握手完成后清除
	                                     */

	/* === 握手状态和时间信息 === */
	enum noise_handshake_state state;  /* 当前握手状态
	                                     * 状态：见上面枚举定义
	                                     * 转换：严格按照协议状态机
	                                     * 检查：每次操作前验证合法性
	                                     * 清理：握手完成或失败后重置
	                                     */

	u64 last_initiation_consumption;   /* 最后处理初始化消息的时间
	                                     * 单位：纳秒 (boottime)
	                                     * 用途：防止重放攻击
	                                     * 检查：新消息时间戳必须更新
	                                     * 清理：握手重置时清零
	                                     */

	/* === 身份和密钥关联 === */
	struct noise_static_identity *static_identity;
	                                   /* 本地静态身份指针
	                                    * 不变：握手初始化后不再改变
	                                    * 用途：提供静态密钥对
	                                    * 生命：整个握手过程保持有效
	                                    * 保护：外部确保生命周期安全
	                                    */

	/* === 握手密钥材料 === */
	u8 ephemeral_private[NOISE_PUBLIC_KEY_LEN];
	                                   /* 临时私钥 (握手专用)
	                                    * 长度：32字节 Curve25519私钥
	                                    * 生成：每次握手随机生成
	                                    * 用途：前向安全的密钥协商
	                                    * 安全：握手完成后立即清零
	                                    * 范围：仅在握手过程中使用
	                                    */

	u8 remote_static[NOISE_PUBLIC_KEY_LEN];
	                                   /* 对方静态公钥
	                                    * 不变：握手初始化后不再改变  
	                                    * 来源：配置文件或动态学习
	                                    * 用途：身份验证和密钥协商
	                                    * 验证：通过预共享或签名验证
	                                    */

	u8 remote_ephemeral[NOISE_PUBLIC_KEY_LEN];
	                                   /* 对方临时公钥
	                                    * 来源：握手消息中接收
	                                    * 用途：临时密钥协商
	                                    * 验证：消息MAC保证完整性
	                                    * 清理：握手完成后可清除
	                                    */

	u8 precomputed_static_static[NOISE_PUBLIC_KEY_LEN];
	                                   /* 预计算的静态DH结果
	                                    * 计算：本地静态私钥 × 对方静态公钥
	                                    * 不变：对等体关系建立后不变
	                                    * 优化：避免握手时重复计算
	                                    * 缓存：可长期保存以提升性能
	                                    */

	/* === 预共享密钥 === */
	u8 preshared_key[NOISE_SYMMETRIC_KEY_LEN];
	                                   /* 预共享对称密钥 (可选)
	                                    * 长度：32字节对称密钥
	                                    * 用途：提供额外的认证保护
	                                    * 来源：带外安全分发
	                                    * 混入：在握手第二轮消息中
	                                    * 优势：抗量子计算攻击
	                                    */

	/* === 握手哈希链 === */
	u8 hash[NOISE_HASH_LEN];           /* 握手消息累积哈希
	                                    * 算法：BLAKE2s哈希函数
	                                    * 用途：消息完整性和认证
	                                    * 更新：每个握手消息都更新
	                                    * 最终：用于派生会话密钥
	                                    */

	u8 chaining_key[NOISE_HASH_LEN];   /* 密钥派生链式密钥
	                                    * 算法：HKDF密钥派生函数
	                                    * 用途：逐步混入密钥材料
	                                    * 安全：提供前向和后向安全
	                                    * 最终：派生出最终会话密钥
	                                    */

	/* === 时间戳和索引 === */
	u8 latest_timestamp[NOISE_TIMESTAMP_LEN];
	                                   /* 最新时间戳 (防重放)
	                                    * 格式：TAI64N格式时间戳
	                                    * 长度：12字节
	                                    * 用途：防止握手消息重放
	                                    * 检查：必须严格单调递增
	                                    */

	__le32 remote_index;               /* 对方握手索引
	                                    * 格式：32位小端序整数
	                                    * 来源：握手消息头部
	                                    * 用途：关联握手上下文
	                                    * 回应：在响应消息中使用
	                                    */

	/* === 并发保护锁 === */
	struct rw_semaphore lock;          /* 握手状态保护锁
	                                    * 类型：读写信号量
	                                    * 保护：除不可变字段外的所有成员
	                                    * 不可变：remote_static, precomputed_static_static, static_identity
	                                    * 读锁：状态查询和消息处理
	                                    * 写锁：状态变更和密钥更新
	                                    */
};

