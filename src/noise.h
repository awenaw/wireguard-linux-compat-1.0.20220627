/**
 * struct noise_replay_counter - 重放攻击保护计数器
 * 
 * 功能描述：
 * 该结构体实现了一个高效的重放攻击保护机制，使用滑动窗口算法来跟踪
 * 已接收的数据包序列号，防止攻击者重放旧的数据包。
 * 
 * 工作原理图：
 * ┌─────────────────────────────────────────────────────────────┐
 * │                   重放保护滑动窗口                           │
 * ├─────────────────────────────────────────────────────────────┤
 * │                                                             │
 * │  旧包 ← ← ←     当前窗口     → → → 新包                     │
 * │                                                             │
 * │  [X][X][X] | [✓][ ][✓][✓][ ][✓] | [ ][ ][ ]                │
 * │            |                     |                         │
 * │        拒绝区域            接受区域         未来区域          │
 * │                                                             │
 * │  X = 已拒绝  ✓ = 已接收  [ ] = 可接收                       │
 * └─────────────────────────────────────────────────────────────┘
 * 
 * 数据结构设计：
 * - counter: 64位最大已见序列号
 * - backtrack: 位图数组，标记窗口内已接收的包
 * - lock: 自旋锁保护并发访问
 * 
 * 性能优化：
 * - 使用位操作进行快速查找和设置
 * - 窗口大小可配置 (COUNTER_BITS_TOTAL)
 * - 无需动态内存分配
 */
struct noise_replay_counter {
	u64 counter;                    /* 当前最大已接收序列号 */
	spinlock_t lock;               /* 保护并发访问的自旋锁 */
	unsigned long backtrack[COUNTER_BITS_TOTAL / BITS_PER_LONG];
	                               /* 重放保护位图窗口：
	                                * 每个位标记对应序列号是否已接收
	                                * 使用 unsigned long 数组优化位操作性能
	                                * COUNTER_BITS_TOTAL 定义窗口总大小
	                                */
};

